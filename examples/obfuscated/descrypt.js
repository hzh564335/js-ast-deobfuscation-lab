/**
 * 字符串数组模块 (synthetic / 合成示例)
 * ============================================================
 * 这个文件用于演示 Webpack 风格混淆器常见的"字符串外置"模式:
 *
 *   - 业务代码里所有字符串/常量都被抽到独立的 IIFE 中,
 *     按下标导出为多个数组 (例 n / e / r);
 *   - 主代码通过 n[0]、e[3]、r[7] 这类 MemberExpression 引用,
 *     令源码静态阅读时几乎看不到任何有意义的字面量。
 *
 * 商业级混淆器(Webpack obfuscator-loader、obfuscator.io 等)产出的
 * 字符串数组通常上千项,且会混入大量噪声字符串。此处只放刚够 demo 跑
 * 通流程的几项,纯学习用途,无任何真实业务字符串。
 */

!function (n, e, r) {
    module.exports = { n, e, r };
}(
    // n: 业务标识符相关字符串
    [
        'add',          // n[0]
        'sub',          // n[1]
        'multiply',     // n[2]
        'unknown op',   // n[3]
        'calculate',    // n[4]
        ',',            // n[5]  -- split 分隔符
    ],
    // e: 通用工具字符串
    [
        'exports',      // e[0]
        'length',       // e[1]
        '',             // e[2]
        16,             // e[3]  -- parseInt radix
        '|',            // e[4]  -- join 分隔符
    ],
    // r: 数字常量
    [
        0,              // r[0]
        1,              // r[1]
        2,              // r[2]
    ]
);
